/**
 * Helper to fetch a high-res photo for any destination and category
 */
export function getDestinationPhoto(destinationName = "", category = "hero") {
  const norm = String(destinationName).toLowerCase().trim();
  let matchKey = "pondicherry";

  if (norm.includes("pondicherry") || norm.includes("puducherry")) matchKey = "pondicherry";
  else if (norm.includes("goa")) matchKey = "goa";
  else if (norm.includes("manali") || norm.includes("himachal")) matchKey = "manali";
  else if (norm.includes("wayanad") || norm.includes("kerala")) matchKey = "wayanad";
  else if (norm.includes("bali")) matchKey = "bali";
  else if (norm.includes("jaipur") || norm.includes("rajasthan")) matchKey = "jaipur";

  const profile = DESTINATION_PHOTOS[matchKey] || DESTINATION_PHOTOS.pondicherry;
  return profile[category] || profile.hero;
}

